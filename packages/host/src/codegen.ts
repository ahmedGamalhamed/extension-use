/**
 * Turn `runtime.describe` output into TypeScript types for a typed client:
 *
 *   import type { HostActions } from "./extension-actions";
 *   const ext = await connect<CoreActions & HostActions>(frame());
 *   await ext.app.save({ note: "…" }); // typed
 */
import { coreActionSchemas } from "@extension-use/protocol/schemas";

type JsonSchema = {
  type?: string | string[];
  properties?: Record<string, JsonSchema>;
  required?: string[];
  items?: JsonSchema;
  enum?: unknown[];
  const?: unknown;
  anyOf?: JsonSchema[];
  oneOf?: JsonSchema[];
  allOf?: JsonSchema[];
  additionalProperties?: boolean | JsonSchema;
  description?: string;
  $ref?: string;
  nullable?: boolean;
};

export interface DescribeOutput {
  host: { id: string; name?: string; version?: string };
  actions: { name: string; description: string; where: string; input: JsonSchema; output: JsonSchema }[];
}

const IDENT = /^[A-Za-z_$][\w$]*$/;
const key = (k: string) => (IDENT.test(k) ? k : JSON.stringify(k));

export function jsonSchemaToTs(schema: JsonSchema | boolean | undefined, indent = ""): string {
  if (schema === true || schema === undefined) return "unknown";
  if (schema === false) return "never";
  if (schema.$ref) return "unknown"; // recursive types (only the snapshot tree today)
  if (schema.const !== undefined) return JSON.stringify(schema.const);
  if (schema.enum) return schema.enum.map((e) => JSON.stringify(e)).join(" | ");
  const union = schema.anyOf ?? schema.oneOf;
  if (union) return union.map((s) => wrap(jsonSchemaToTs(s, indent))).join(" | ");
  if (schema.allOf) return schema.allOf.map((s) => wrap(jsonSchemaToTs(s, indent))).join(" & ");

  const types = Array.isArray(schema.type) ? schema.type : schema.type ? [schema.type] : [];
  if (types.length > 1) return types.map((t) => jsonSchemaToTs({ ...schema, type: t }, indent)).join(" | ");
  switch (types[0]) {
    case "string":
      return "string";
    case "number":
    case "integer":
      return "number";
    case "boolean":
      return "boolean";
    case "null":
      return "null";
    case "array":
      return `${wrap(jsonSchemaToTs(schema.items, indent))}[]`;
    case "object":
    case undefined: {
      if (!schema.properties && types[0] === undefined) return "unknown";
      const props = Object.entries(schema.properties ?? {});
      const extra = schema.additionalProperties;
      if (!props.length) return extra && extra !== true ? `Record<string, ${jsonSchemaToTs(extra, indent)}>` : "Record<string, unknown>";
      const inner = indent + "  ";
      const lines = props.map(([k, v]) => {
        const doc = v.description ? `${inner}/** ${v.description.replace(/\*\//g, "*\\/")} */\n` : "";
        return `${doc}${inner}${key(k)}${(schema.required ?? []).includes(k) ? "" : "?"}: ${jsonSchemaToTs(v, inner)};`;
      });
      return `{\n${lines.join("\n")}\n${indent}}`;
    }
    default:
      return "unknown";
  }
}

function wrap(t: string) {
  return / [|&] /.test(t) && !t.startsWith("{") ? `(${t})` : t;
}

/** Generate a .ts module with an action map type. Built-in actions are skipped unless `all` is set. */
export function generateTypes(describe: DescribeOutput, options: { all?: boolean; typeName?: string } = {}): string {
  const typeName = options.typeName ?? "HostActions";
  const actions = describe.actions.filter((a) => options.all || !(a.name in coreActionSchemas)).sort((a, b) => a.name.localeCompare(b.name));
  const body = actions
    .map((a) => {
      const doc = a.description ? `  /** ${a.description.replace(/\*\//g, "*\\/")} */\n` : "";
      return `${doc}  ${JSON.stringify(a.name)}: {\n    input: ${jsonSchemaToTs(a.input, "    ")};\n    output: ${jsonSchemaToTs(a.output, "    ")};\n  };`;
    })
    .join("\n");
  const host = describe.host.name ? `${describe.host.name} (${describe.host.id})` : describe.host.id;
  return `// Generated by \`extension-use codegen\` from ${host}${describe.host.version ? ` ${describe.host.version}` : ""}. Do not edit.
// Use it with: connect<CoreActions & ${typeName}>(transport)

export type ${typeName} = {
${body}
};
`;
}
